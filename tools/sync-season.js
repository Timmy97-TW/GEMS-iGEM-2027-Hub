// Rebuilds data/season.js from the GEMS iGEM System site's assets/data.js, so the hub never
// retypes a node, role, rule or folder. The system site is the source; this file only copies.
//
//   node tools/sync-season.js [path-or-url] > data/season.js     (the GitHub Action runs this daily)
//   jsc  tools/sync-season.js -- <path>     > data/season.js     (macOS without node)
//
// With no argument, node reads the live site.
const SOURCE = "https://timmy97-tw.github.io/GEMS-iGEM-SYSTEM/assets/data.js";
const PICK = `({
  nodes: TIMELINE.filter(m => m.n).map(m => ({ n: m.n, date: m.date, dl: m.dl, lane: m.lane, t: m.t, pass: m.pass, d: m.d, owner: m.owner, ok: m.ok })),
  bands: YEAR_BANDS.map(b => ({ kind: b.kind, s: b.s, e: b.e, n: b.n, now: b.now })),
  roles: PEOPLE.roles.map(r => ({ code: r.code, kind: r.kind, group: r.group, name: r.name, seats: r.seats, sec: r.sec, when: r.when, own: r.own,
    week: r.week, rhythm: r.rhythm, nodes: r.nodes, tabs: r.tabs, folders: r.folders, backup: typeof r.backup === "string" ? r.backup : undefined })),
  chores: PEOPLE.chores,
  rituals: RITUALS,
  principles: PRINCIPLES,
  gates: GATES.map(g => ({ ids: g.ids, t: g.t, rule: g.rule, who: g.who })),
  ids: ID_SYSTEM,
  chains: ID_CHAINS,
  layers: SYS_LAYERS,
  hubTabs: HUB_TABS,
  drive: DRIVE.map(f => ({ id: f.id, name: f.name, drive: f.drive, kids: f.kids, holds: f.holds, edit: f.edit, rule: f.rule })),
  docs: YEAR_ITEMS.map(x => ({ id: x.id, lane: x.lane, d: x.d, end: x.end, dl: typeof x.dl === "string" ? x.dl : undefined, n: x.n, who: x.who, reads: x.reads, loc: x.loc, tpl: x.tpl, rule: x.rule }))
})`;

const build = src => {
  const season = (0, eval)(src + "\n;" + PICK);
  if (!season.nodes.length || !season.roles.length) throw new Error("data.js parsed but nodes or roles came back empty");
  return "// GENERATED by tools/sync-season.js from the GEMS iGEM System site. Do not edit by hand:\n"
    + "// change assets/data.js in GEMS-iGEM-SYSTEM, then rerun the sync (the daily Action does it too).\n"
    + "const SEASON = {\n" + Object.entries(season).map(([k, v]) => ` ${k}: [\n${v.map(x => "  " + JSON.stringify(x)).join(",\n")}\n ]`).join(",\n") + "\n};\n";
};

if (typeof process !== "undefined" && process.versions && process.versions.node) {
  const from = process.argv[2] || SOURCE;
  const read = /^https?:/.test(from)
    ? fetch(from).then(r => { if (!r.ok) throw new Error(from + " returned " + r.status); return r.text(); })
    : Promise.resolve(require("fs").readFileSync(from, "utf8"));
  read.then(src => process.stdout.write(build(src))).catch(e => { console.error(e.message); process.exit(1); });
} else {
  print(build(readFile(arguments[0])));
}
