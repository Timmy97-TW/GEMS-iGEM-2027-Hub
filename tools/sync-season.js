// Rebuilds data/season.js from the System site's assets/data.js, so the hub never retypes a
// milestone, seat, rule or folder. The System site is the source; this file only copies.
// Run it through tools/sync.sh, which keeps the last good copy when anything fails.

// What the hub reads, and nothing else. TIMELINE, YEAR_BANDS and PEOPLE.roles are required;
// a missing optional list comes back empty and the Guide leaves that part out.
const PICK = `(() => {
  const opt = f => { try { const v = f(); return Array.isArray(v) ? v : []; } catch (e) { return []; } };
  return {
    nodes: TIMELINE.filter(m => m.n).map(m => ({ n: m.n, date: m.date, dl: m.dl, lane: m.lane, t: m.t, pass: m.pass, d: m.d, owner: m.owner, ok: m.ok })),
    bands: YEAR_BANDS.map(b => ({ kind: b.kind, s: b.s, e: b.e, n: b.n, now: b.now })),
    roles: PEOPLE.roles.map(r => ({ code: r.code, group: r.group, name: r.name, when: r.when, own: r.own, week: r.week, backup: typeof r.backup === "string" ? r.backup : undefined })),
    chores: opt(() => PEOPLE.chores),
    rituals: opt(() => RITUALS),
    principles: opt(() => PRINCIPLES),
    gates: opt(() => GATES).map(g => ({ t: g.t, rule: g.rule, who: g.who })),
    ids: opt(() => ID_SYSTEM),
    chains: opt(() => ID_CHAINS),
    layers: opt(() => SYS_LAYERS),
    hubTabs: opt(() => HUB_TABS),
    drive: opt(() => DRIVE).map(f => ({ name: f.name, holds: f.holds })),
    docs: opt(() => YEAR_ITEMS).filter(x => !["igem", "gate"].includes(x.lane)).map(x => ({ lane: x.lane, n: x.n, who: x.who, reads: x.reads, loc: x.loc }))
  };
})()`;

const build = src => {
  const season = (0, eval)(src + "\n;" + PICK);
  const bad = [];
  if (!season.nodes.length) bad.push("no milestones");
  season.nodes.forEach(n => { if (!/^\d{4}-\d\d-\d\d$/.test(n.date) || !n.t) bad.push("milestone " + n.n + " has no date or no title"); });
  if (!season.bands.some(b => b.kind === "phase" && b.s && b.e)) bad.push("no phases");
  if (!season.roles.some(r => r.code && r.name)) bad.push("no seats");
  if (bad.length) throw new Error("data.js does not look right: " + bad.join("; "));
  return "// GENERATED by tools/sync-season.js from the GEMS iGEM System site. Do not edit by hand:\n"
    + "// change assets/data.js in GEMS-iGEM-SYSTEM, then run tools/sync.sh (the nightly Action does it too).\n"
    + "const SEASON = {\n" + Object.entries(season).map(([k, v]) => ` ${k}: [\n${v.map(x => "  " + JSON.stringify(x)).join(",\n")}\n ]`).join(",\n") + "\n};\n";
};

// node tools/sync-season.js <path>   |   jsc tools/sync-season.js -- <path>
if (typeof process !== "undefined" && process.versions && process.versions.node) {
  try { process.stdout.write(build(require("fs").readFileSync(process.argv[2], "utf8"))); }
  catch (e) { console.error("sync-season: " + e.message); process.exit(1); }
} else {
  print(build(readFile(arguments[0])));
}
